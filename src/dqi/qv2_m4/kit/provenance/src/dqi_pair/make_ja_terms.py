"""Lane dqi_pair: write tools/dqi_pair/ja_terms.py = {s: terms} for every s = t_old xor t_new of our node order
(doubles on nodes 0..16, t = 2i): public J_A (lane kernel_flip / dqi890 exports, from Syed Asad Ali's compiled v13
decoder, Apache-2.0) where exported, else the 198-AND fallback (two K products). Each verified with kernels.verify."""
import sys, json, hashlib
sys.path.insert(0, '<REPO>/src/dqi_kern')
import kernels as K
d = K.load()
need = sorted({2 * (a ^ b) for a in range(17) for b in range(a)})
out, info = {}, {}
for s in need:
    terms = K.get_ja(d, s)
    v = K.verify(terms, K.map_ja(s), nrand=2000)
    assert v['ok'], (s, v)
    out[s] = [list(t) for t in terms]; info[s] = len(terms)
src = json.dumps(d.get('JA', {}).get('30', {}).get('source', '')) if d.get('JA') else ''
kh = hashlib.sha256(open('<REPO>/src/dqi_kern/kernels.json', 'rb').read()).hexdigest()
with open('<REPO>/tools/dqi_pair/ja_terms.py', 'w') as f:
    f.write('# SPDX-License-Identifier: Apache-2.0\n# ' + d['credit'] + '\n')
    f.write(f'# J_A[s]: head X in value view, target (d, e): d ^= X n, e ^= sqrt((a + kappa(s) b) + b theta) n.\n'
            f'# Generated by src/dqi_pair/make_ja_terms.py from src/dqi_kern/kernels.json sha256 {kh};\n'
            f'# public kernels for s in {sorted(int(k) for k in d.get("JA", {}))}, 198-AND fallback otherwise. Ranks: {info}\n')
    f.write('TERMS = ' + json.dumps({str(k): v for k, v in out.items()}) + '\n')
print(info, sum(info[s] * c for s, c in __import__('collections').Counter(2 * (a ^ b) for a in range(17) for b in range(a)).items()))
